"""Generate party/core/unicode13.generated.js from the oracle's own unicodedata.

The pure-JS core must reproduce CPython 3.9 text semantics exactly, so every
table comes from the interpreter that runs the accepted Python server, never
from the host ICU (which tracks a newer Unicode version and drifts):

* per-code-point NFD and NFKD expansions (Hangul syllables are algorithmic)
* canonical combining classes, primary composites
* code points rejected by textutil.clean_text (Cc/Cs/Co/Cn unless isspace,
  plus the bidi controls)
* str.isspace / str.split / str.strip whitespace
* str.casefold expansions
* str.upper expansions that can survive manager.get_room's [A-Z2-9]{6} match

Usage: python3 -I -B gen_unicode_tables.py OUT.js
Refuses to run unless unicodedata reports 13.0.0.
"""

import hashlib
import json
import sys
import unicodedata

PINNED = "13.0.0"
SBASE, SCOUNT = 0xAC00, 11172
CODE_CHARS = set("ABCDEFGHIJKLMNOPQRSTUVWXYZ23456789")
BIDI = set(range(0x202A, 0x202F)) | set(range(0x2066, 0x206A))


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        hit = pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out += [start, cp - 1]
            start = None
    if start is not None:
        out += [start, 0x10FFFF]
    return out


def expansion_table(fn):
    flat = []
    for cp in range(0x110000):
        if SBASE <= cp < SBASE + SCOUNT:
            continue
        mapped = fn(chr(cp))
        if mapped is not None and mapped != chr(cp):
            flat += [cp, len(mapped)] + [ord(c) for c in mapped]
    return flat


def main(out_path):
    if unicodedata.unidata_version != PINNED:
        sys.exit("unicodedata %s is not the pinned %s" % (unicodedata.unidata_version, PINNED))

    nfd = expansion_table(lambda c: unicodedata.normalize("NFD", c))
    # NFKD entries only where they differ from NFD; the core falls back to NFD.
    nfkd = expansion_table(lambda c: unicodedata.normalize("NFKD", c)
                           if unicodedata.normalize("NFKD", c) != unicodedata.normalize("NFD", c) else None)

    ccc, run = [], None
    for cp in range(0x110001):
        value = unicodedata.combining(chr(cp)) if cp < 0x110000 else -1
        if run is not None and value == run[2]:
            run[1] = cp
            continue
        if run is not None and run[2] != 0:
            ccc += run
        run = [cp, cp, value]

    comp = []
    for cp in range(0x110000):
        dec = unicodedata.decomposition(chr(cp))
        if not dec or dec.startswith("<"):
            continue
        parts = [int(x, 16) for x in dec.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            comp += [parts[0], parts[1], cp]

    def rejected(cp):
        ch = chr(cp)
        if cp in BIDI:
            return True
        return unicodedata.category(ch) in ("Cc", "Cs", "Co", "Cn") and not ch.isspace()

    reject = ranges(rejected)
    ws = [cp for cp in range(0x110000) if chr(cp).isspace()]
    fold = expansion_table(lambda c: c.casefold())
    upper_code = []
    for cp in range(0x110000):
        ch = chr(cp)
        if ch in CODE_CHARS:
            continue
        up = ch.upper()
        if up and all(u in CODE_CHARS for u in up):
            upper_code += [cp, len(up)] + [ord(u) for u in up]

    tables = {"unidata": unicodedata.unidata_version, "python": sys.version.split()[0],
              "nfd": nfd, "nfkd": nfkd, "ccc": ccc, "comp": comp, "reject": reject,
              "ws": ws, "fold": fold, "upperCode": upper_code}
    body = json.dumps(tables, separators=(",", ":"), sort_keys=True)
    digest = hashlib.sha256(body.encode("ascii")).hexdigest()
    with open(out_path, "w", encoding="ascii", newline="\n") as handle:
        handle.write("// GENERATED by party/core/tools/gen_unicode_tables.py. Do not edit.\n")
        handle.write("// Source: CPython %s unicodedata %s (oracle runtime). tables-sha256: %s\n"
                     % (tables["python"], tables["unidata"], digest))
        handle.write("var MajlisUnicode13Tables = %s;\n" % body)
    print("wrote %s sha256(tables)=%s nfd=%d nfkd=%d ccc_ranges=%d comp=%d reject_ranges=%d ws=%d fold=%d upper=%d"
          % (out_path, digest, len(nfd), len(nfkd), len(ccc) // 3, len(comp) // 3, len(reject) // 2,
             len(ws), len(fold), len(upper_code)))


if __name__ == "__main__":
    main(sys.argv[1])
