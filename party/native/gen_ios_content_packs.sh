#!/bin/sh
# Deterministically bundles the exact two accepted content packs
# (PartyHost.swift's `implementedModes = ["who_am_i", "feud"]`) into a plain
# directory the iOS app bundles as a resource folder and binds
# PartyHost(contentDir:) to at runtime. Mirrors gen_ios_web_resources.sh's
# pattern for the web surface: copy only the reviewed packs, never a whole
# directory tree, and fail loudly and specifically rather than producing a
# bundle that is silently missing or wrong.
#
#   party/native/gen_ios_content_packs.sh OUT_DIR
#
# party/core/majlis-core.js's parsePack (called from PartyHost.init's
# engine "init" call) is the actual schema authority and already rejects a
# structurally invalid pack at app launch; this script's own check is a
# narrower, fast sanity gate run at build time so a missing file, a pack
# for the wrong mode, or a file that isn't even valid JSON fails the build
# immediately with a clear message, instead of shipping a bundle that only
# fails once the app tries to host a room.
set -eu
OUT=${1:?usage: gen_ios_content_packs.sh OUT_DIR}
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
CONTENT="$ROOT/party/content"
MODES="who_am_i feud"

rm -rf "$OUT"
mkdir -p "$OUT"

for mode in $MODES; do
  src="$CONTENT/$mode.json"
  if [ ! -f "$src" ]; then
    echo "gen_ios_content_packs.sh: missing required content pack: $src" >&2
    exit 1
  fi
  if ! "${PYTHON3:-python3}" -I -c "
import json, sys
with open('$src', encoding='utf-8') as f:
    data = json.load(f)
if data.get('mode') != '$mode':
    sys.exit('pack declares mode=' + repr(data.get('mode')) + ', expected $mode')
if data.get('schemaVersion') != 1:
    sys.exit('pack schemaVersion=' + repr(data.get('schemaVersion')) + ', expected 1')
" 2> /tmp/gen_ios_content_packs_err.$$; then
    echo "gen_ios_content_packs.sh: $src failed validation: $(cat /tmp/gen_ios_content_packs_err.$$)" >&2
    rm -f /tmp/gen_ios_content_packs_err.$$
    exit 1
  fi
  rm -f /tmp/gen_ios_content_packs_err.$$
  cp "$src" "$OUT/$mode.json"
done

{
  echo "Generated by party/native/gen_ios_content_packs.sh. Do not edit by hand."
  echo "Accepted content packs bundled for PartyHost.swift's implementedModes."
  echo "sha256  file"
  for mode in $MODES; do
    shasum -a 256 "$OUT/$mode.json" | awk -v f="$mode.json" '{print $1 "  " f}'
  done
} > "$OUT/MANIFEST.txt"
