#!/bin/sh
# Deterministically generates the EngineSource embedding of the three reviewed
# JS files (party/core/unicode13.generated.js, party/core/majlis-core.js,
# party/native/majlis-native.js) as plain base64 text in a Swift source file.
#
#   party/native/gen_embedded_sources.sh OUT_SWIFT_FILE
#
# Shared by party/native/build.sh (macOS CLI) and the Majlis iOS target's
# "Generate embedded party sources" build phase (majlis-ios/project.yml), so
# both ship the exact same reviewed bytes from one place. Pure text
# generation only: no compiler is invoked here.
set -eu
OUT=${1:?usage: gen_embedded_sources.sh OUT_SWIFT_FILE}
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
mkdir -p "$(dirname "$OUT")"
{
  echo "// GENERATED by party/native/gen_embedded_sources.sh. Do not edit."
  echo "import Foundation"
  echo "enum EmbeddedSources {"
  echo "    static func decode(_ b64: String) -> String {"
  echo "        String(decoding: Data(base64Encoded: b64)!, as: UTF8.self)"
  echo "    }"
  echo "    static let all: [EngineSource] = ["
  for f in party/core/unicode13.generated.js party/core/majlis-core.js party/native/majlis-native.js; do
    sum=$(shasum -a 256 "$ROOT/$f" | cut -d' ' -f1)
    printf '        // %s sha256 %s\n' "$f" "$sum"
    printf '        EngineSource(name: "%s", text: decode("%s")),\n' "$(basename "$f")" "$(base64 < "$ROOT/$f" | tr -d '\n')"
  done
  echo "    ]"
  echo "}"
} > "$OUT"
