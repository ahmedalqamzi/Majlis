#!/bin/sh
# Deterministically copies the exact production player surface
# (party/native/Sources/Support.swift StaticRoot.productionFiles) into a
# plain directory the iOS app bundles as a resource folder and binds
# StaticRoot(directory:) to at runtime. Copies only those files — never the
# whole party/web tree, which also holds party/web/sim and party/web/tests
# (harness-only JS the L02A brief requires excluded from the app target) and
# the operator/display pages (host.html, tv.html, index.html) this surface
# never serves.
#
#   party/native/gen_ios_web_resources.sh OUT_DIR
#
# Shared by a future "Generate party web resources" Xcode build phase
# (majlis-ios/project.yml) so the bundled resource always matches the
# reviewed production surface; no compiler is invoked here.
set -eu
OUT=${1:?usage: gen_ios_web_resources.sh OUT_DIR}
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
WEB="$ROOT/party/web"

rm -rf "$OUT"
mkdir -p "$OUT/css" "$OUT/js"

cp "$WEB/play.html" "$OUT/play.html"
cp "$WEB/css/party.css" "$OUT/css/party.css"
for n in play modes views qr session transport ui; do
  cp "$WEB/js/$n.js" "$OUT/js/$n.js"
done

{
  echo "Generated by party/native/gen_ios_web_resources.sh. Do not edit by hand."
  echo "Files copied (production player surface only):"
  find "$OUT" -type f ! -name MANIFEST.txt | sed "s#^$OUT/##" | sort
} > "$OUT/MANIFEST.txt"
